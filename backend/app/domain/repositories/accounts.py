from typing import Any, Protocol


class AccountRepository(Protocol):
    def new_identity(self, **values: Any) -> object: ...
    def identity(self, provider: str, subject: str) -> Any: ...
    def identities_for_user(self, user_id: int) -> list: ...
    def cancel_social_access(self, user_id: int) -> None: ...
    def new_oauth_attempt(self, **values: Any) -> object: ...
    def oauth_attempt(self, state_hash: str) -> Any: ...
    def claim_oauth_attempt(self, attempt_id: int) -> bool: ...
    def purge_oauth_attempts(self) -> None: ...
    def new_session(self, **values: Any) -> object: ...
    def new_token(self, **values: Any) -> object: ...
    def new_message(self, **values: Any) -> object: ...
    def session_by_hash(self, digest: str) -> Any: ...
    def token_by_hash(self, digest: str, purpose: str) -> Any: ...
    def sessions_for_user(self, user_id: int) -> list: ...
    def claim_token(self, token_id: int) -> bool: ...
    def claim_mfa(self, user_id: int, previous: int | None, counter: int, recovery_codes: list | None = None) -> bool: ...
    def revoke_sessions(self, user_id: int, except_id: int | None = None) -> None: ...
    def messages(self, limit: int = 50) -> list: ...
    def claim_mail(self, now: Any, lease: str, until: Any) -> Any: ...
    def finish_mail(self, message_id: int, lease: str, **values: Any) -> bool: ...
