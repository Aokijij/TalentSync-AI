from typing import Any, Protocol


class ResumeVersionRepository(Protocol):
    def get(self, version_id: str) -> Any: ...
    def find_request(self, user_id: int, request_key: str) -> Any: ...
    def for_job(self, user_id: int, job_id: int) -> list[Any]: ...
    def count_for_job(self, user_id: int, job_id: int) -> int: ...
    def new(self, **values) -> Any: ...
