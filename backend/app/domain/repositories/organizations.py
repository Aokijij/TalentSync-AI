from typing import Any, Protocol


class OrganizationRepository(Protocol):
    def invitations(self, company_id: int) -> list: ...
    def cancel_invitation(self, company_id: int, invitation_id: int) -> bool: ...
    def member_for_user(self, user_id: int) -> Any: ...
    def members(self, company_id: int) -> list: ...
    def member(self, company_id: int, member_id: int) -> Any: ...
    def team_page(self, company_id: int, *, kind, status, search, page, page_size) -> dict: ...
    def new_member(self, **values: Any) -> Any: ...
    def new_invitation(self, **values: Any) -> Any: ...
    def invitation(self, digest: str) -> Any: ...
    def consume_invitation(self, invitation_id: int) -> bool: ...
    def verification_queue(self) -> list: ...
    def verification_page(self, *, status, search, page, page_size) -> dict: ...
