import { test, expect } from "@playwright/test";

for (const theme of ["light", "dark"]) for (const width of [360, 1280]) test(`Administrative vacancy design and profession suggestions · ${theme} · ${width}`, async ({ page }) => {
  await page.setViewportSize({ width, height: 1100 });
  const errors = [], writes = [];
  page.on("pageerror", error => errors.push(error.message));
  const job = { id: 41, title: "Analista de operaciones", company_id: 21, company_name: "Empresa de ejemplo", status: "active", source_kind: "external", source_portal: "Portal original", external_url: "https://example.test/jobs/41", description: "Preparar reportes y revisar la calidad de los registros de operaciones del equipo.", requirements: "Experiencia revisando información y preparando reportes de seguimiento de operaciones.", skills: ["sql", "excel", "documentacion"], modality: "unspecified", languages: [], benefits: [], quality_details: {}, external_available: true, external_check_state: "verified", moderation_revision: 0, review: { can_publish: true, can_activate: true, checks: [{ label: "Estado en el catálogo", passed: true }, { label: "Vigencia confirmada recientemente", passed: true }] } };
  await page.route("**/api/v1/**", route => {
    const request = route.request(), path = new URL(request.url()).pathname;
    if (path.endsWith("/hiring/education/catalog")) return route.fulfill({ json: { items: [{ label: "Contaduría Pública", aliases: ["contaduria", "contabilidad", "contaduria publica"] }, { label: "Ingeniería de Sistemas", aliases: ["sistemas", "informática"] }] } });
    if (path.endsWith("/admin/jobs/41/review")) return route.fulfill({ json: job });
    if (request.method() === "PATCH") { writes.push(request.postDataJSON()); return route.fulfill({ json: { ...job, moderation_revision: 1 } }); }
    if (path.endsWith("/admin/stats")) return route.fulfill({ json: { jobs: 1 } });
    return route.fulfill({ json: { items: [job], total: 1, configured: false } });
  });
  await page.goto(`/quality/?adminRecords=1&theme=${theme}`);
  await page.getByRole("navigation", { name: "Recursos administrativos", exact: true }).getByRole("button", { name: /Vacantes/ }).click();
  await expect(page.getByRole("link", { name: "Ver vacante completa", exact: true })).toHaveAttribute("href", "/vacantes/41");
  await page.getByRole("button", { name: "Ver ficha", exact: true }).click();
  const dialog = page.getByRole("dialog", { name: "Revisar vacante", exact: true });
  const full = dialog.getByRole("link", { name: /Ver vacante completa/ });
  await expect(full).toHaveAttribute("target", "_blank");
  await expect(full).toHaveAttribute("href", "/vacantes/41");
  await expect(dialog.getByText("Sin especificar", { exact: true })).toBeVisible();
  await dialog.getByRole("button", { name: "Contenido y edición", exact: true }).click();
  await dialog.getByRole("button", { name: "Editar contenido", exact: true }).click();
  const form = dialog.locator(".external-job-editor");
  await form.getByRole("button", { name: "Requisitos", exact: true }).click();
  await form.getByRole("checkbox", { name: /^Categoría A1:/ }).check();
  await expect(form.getByRole("checkbox", { name: /^Categoría A1:/ })).toBeChecked();
  const picker = form.getByRole("combobox", { name: "Profesiones aceptadas", exact: true });
  const suggestions = form.getByRole("listbox", { name: "Sugerencias de profesiones aceptadas", exact: true });
  await picker.fill("contabilidad");
  await expect(suggestions.getByRole("option")).toHaveCount(1);
  await expect(suggestions.getByRole("option", { name: "Contaduría Pública", exact: true })).toBeVisible();
  await picker.press("ArrowDown");
  await picker.press("Enter");
  await expect(form.getByRole("list", { name: "Profesiones aceptadas: elementos añadidos" })).toContainText("Contaduría Pública");
  await picker.fill("sistemas");
  await picker.press("ArrowDown");
  await expect(suggestions.getByRole("option", { name: "Ingeniería de Sistemas", exact: true })).toBeVisible();
  await dialog.screenshot({ path: `../.local/admin-design-20261104/professions-${theme}-${width}.png` });
  await picker.press("Escape");
  await expect(dialog).toBeVisible();
  await expect(picker).toHaveAttribute("aria-expanded", "false");
  await picker.fill("Diseño de experiencias inmersivas");
  await picker.press("Enter");
  await expect(form.getByRole("list", { name: "Profesiones aceptadas: elementos añadidos" })).toContainText("Diseño de experiencias inmersivas");
  expect(await form.locator("datalist").count()).toBe(0);
  await form.getByRole("button", { name: "Condiciones", exact: true }).click();
  await expect(form.getByRole("button", { name: "Dejar horario sin informar", exact: true })).toBeDisabled();
  await form.getByRole("button", { name: "Escribir horario", exact: true }).click();
  await form.getByRole("textbox", { name: "Describe la jornada", exact: true }).fill("Lunes a viernes de 8:00 a 17:00.");
  await form.getByRole("button", { name: "Dejar horario sin informar", exact: true }).click();
  await expect(form.getByRole("button", { name: "Dejar horario sin informar", exact: true })).toBeDisabled();
  await form.getByRole("textbox", { name: "Qué información contrastaste en la oferta original", exact: true }).fill("Documentos contrastados en los requisitos de la oferta original.");
  await form.getByRole("button", { name: "Guardar contenido", exact: true }).click();
  await expect(dialog.getByRole("button", { name: "Editar contenido", exact: true })).toBeVisible();
  expect(writes[0].fields.quality_details.credential_requirements).toEqual({ driving_categories: ["A1"], professional_cards: ["Contaduría Pública", "Diseño de experiencias inmersivas"] });
  await dialog.getByRole("button", { name: "Publicación", exact: true }).click();
  await dialog.locator(".external-publication").scrollIntoViewIfNeeded();
  await expect(dialog.getByRole("radio", { name: "Publicada", exact: true })).toBeChecked();
  await dialog.getByRole("radio", { name: "Borrador", exact: true }).check();
  await expect(dialog.getByRole("button", { name: "Guardar estado", exact: true })).toBeVisible();
  await dialog.screenshot({ path: `../.local/admin-design-20261104/publication-${theme}-${width}.png` });
  await page.evaluate(() => { document.documentElement.style.fontSize = "200%"; });
  expect(await dialog.evaluate(node => node.scrollWidth - node.clientWidth)).toBeLessThanOrEqual(1);
  expect(errors).toEqual([]);
});
